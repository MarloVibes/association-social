async function updateEraRosters() {
  const eras = ['magic_bird', 'jordan', 'kobe', 'lebron', 'steph'];
  let updated = 0;
  let stillMissing = [];

  for (const era of eras) {
    const teamsSnap = await getDocs(collection(db, 'era_rosters', era, 'teams'));
    for (const teamDoc of teamsSnap.docs) {
      const data = teamDoc.data();
      let changed = false;
      const updatedPlayers = (data.players || []).map(player => {
        if (player.birth_year) return player; // already has birth year
        const info = PLAYER_DATA[player.full_name];
        if (info) {
          changed = true;
          return { ...player, birth_year: info.birth, retirement_year: info.retired };
        } else {
          if (!stillMissing.includes(player.full_name)) stillMissing.push(player.full_name);
          return player;
        }
      });

      if (changed) {
        await updateDoc(doc(db, 'era_rosters', era, 'teams', teamDoc.id), { players: updatedPlayers });
        updated++;
        process.stdout.write('.');
      }
    }
  }

  console.log(`\nUpdated ${updated} teams`);
  if (stillMissing.length > 0) {
    console.log('Still missing:', stillMissing);
  } else {
    console.log('All players have birth years!');
  }
  process.exit(0);
}

updateEraRosters().catch(e => { console.error(e); process.exit(1); });
