async function updateEraRosters() {
  const eras = ['magic_bird', 'jordan', 'kobe', 'lebron', 'steph'];
  let updated = 0;
  let notFound = [];

  for (const era of eras) {
    const teamsSnap = await getDocs(collection(db, 'era_rosters', era, 'teams'));
    for (const teamDoc of teamsSnap.docs) {
      const data = teamDoc.data();
      let changed = false;
      const updatedPlayers = (data.players || []).map(player => {
        const info = PLAYER_DATA[player.full_name];
        if (info) {
          changed = true;
          return {
            ...player,
            birth_year: info.birth,
            retirement_year: info.retired,
          };
        } else {
          if (!notFound.includes(player.full_name)) {
            notFound.push(player.full_name);
          }
          return player;
        }
      });

      if (changed) {
        await updateDoc(doc(db, 'era_rosters', era, 'teams', teamDoc.id), {
          players: updatedPlayers,
        });
        updated++;
        process.stdout.write('.');
      }
    }
    console.log(` ${era} done`);
  }

  console.log(`\nUpdated ${updated} team docs`);
  if (notFound.length > 0) {
    console.log('\nPlayers not found in PLAYER_DATA (need birth years added):');
    notFound.forEach(n => console.log(' -', n));
  }
  process.exit(0);
}

updateEraRosters().catch(e => { console.error(e); process.exit(1); });
